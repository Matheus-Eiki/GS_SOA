-- 1. TABELA DE USUARIOS


CREATE TABLE USUARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE,
    TELEFONE VARCHAR2(20) NOT NULL,
    DATA_NASCIMENTO DATE,
    ENDERECO VARCHAR2(250),
    MORA_SOZINHO NUMBER(1) DEFAULT 0 NOT NULL,
    NECESSIDADES_ACESSIBILIDADE VARCHAR2(500),
    SENHA_HASH VARCHAR2(255),
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT CK_CT_USR_SOZINHO
    CHECK (MORA_SOZINHO IN (0, 1)),

    CONSTRAINT CK_CT_USR_ATIVO
    CHECK (ATIVO IN (0, 1))
);


-- 2. TABELA DE CONTATOS DE EMERGENCIA

CREATE TABLE CONTATOS_EMERGENCIA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL,
    NOME VARCHAR2(120) NOT NULL,
    PARENTESCO VARCHAR2(60),
    TELEFONE VARCHAR2(20) NOT NULL,
    EMAIL VARCHAR2(150),
    PRINCIPAL NUMBER(1) DEFAULT 0 NOT NULL,

    CONSTRAINT FK_CONTATO_USUARIO
    FOREIGN KEY (USUARIO_ID)
    REFERENCES USUARIOS(ID),

    CONSTRAINT CK_CONTATO_PRINCIPAL
    CHECK (PRINCIPAL IN (0, 1))
);


-- 3. TABELA DE ACOMPANHAMENTOS

CREATE TABLE ACOMPANHAMENTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL,
    RESPONSAVEL VARCHAR2(120),
    TIPO VARCHAR2(60) NOT NULL,
    DESCRICAO VARCHAR2(500),
    DATA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'REGISTRADO' NOT NULL,

    CONSTRAINT FK_ACOMP_USUARIO
    FOREIGN KEY (USUARIO_ID)
    REFERENCES USUARIOS(ID),

    CONSTRAINT CK_ACOMP_STATUS
    CHECK (STATUS IN ('REGISTRADO', 'CANCELADO'))
);


-- 4. TABELA DE ALERTAS

CREATE TABLE ALERTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL,
    CONTATO_ID NUMBER,
    TIPO VARCHAR2(40) NOT NULL,
    DESCRICAO VARCHAR2(500) NOT NULL,
    DATA_ALERTA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ABERTO' NOT NULL,

    CONSTRAINT FK_ALERTA_USUARIO
    FOREIGN KEY (USUARIO_ID)
    REFERENCES USUARIOS(ID),

    CONSTRAINT FK_ALERTA_CONTATO
    FOREIGN KEY (CONTATO_ID)
    REFERENCES CONTATOS_EMERGENCIA(ID),

    CONSTRAINT CK_ALERTA_TIPO
    CHECK (TIPO IN ('EMERGENCIA', 'ASSISTENCIA', 'LEMBRETE')),

    CONSTRAINT CK_ALERTA_STATUS
    CHECK (STATUS IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO'))
);


-- ==========================================
-- INDICES PARA CONSULTAS
-- ==========================================

CREATE INDEX IDX_CONTATO_USUARIO
ON CONTATOS_EMERGENCIA(USUARIO_ID);

CREATE INDEX IDX_ACOMP_USUARIO
ON ACOMPANHAMENTOS(USUARIO_ID);

CREATE INDEX IDX_ALERTA_USUARIO
ON ALERTAS(USUARIO_ID);